#!/usr/bin/env bash
# Install tools/check_workspace.py as a git pre-commit hook.
#
# Idempotent: re-running won't duplicate or break an existing hook.
# Refuses to overwrite a non-Crucible hook without --force.
#
# Usage:
#   bash tools/install_precommit.sh           # install
#   bash tools/install_precommit.sh --force   # overwrite existing hook
#   bash tools/install_precommit.sh --dry-run # show what would happen

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HOOK_PATH="${REPO_ROOT}/.git/hooks/pre-commit"
SENTINEL="# crucible-precommit-v1"

FORCE=0
DRY_RUN=0
for arg in "$@"; do
    case "$arg" in
        --force) FORCE=1 ;;
        --dry-run) DRY_RUN=1 ;;
        *) echo "unknown flag: $arg" >&2; exit 2 ;;
    esac
done

if [[ ! -d "${REPO_ROOT}/.git" ]]; then
    echo "no .git directory at ${REPO_ROOT}; not a git checkout?" >&2
    exit 1
fi

# Build the new hook content.
read -r -d '' HOOK_CONTENT <<EOF || true
#!/usr/bin/env bash
${SENTINEL}
# Auto-generated by tools/install_precommit.sh — runs the workspace
# consistency checks (schema-version drift, fixture validity, manifest
# format, pydantic pin, doc-links, profile-shape). Skip with
#   git commit --no-verify
# but understand what you're skipping first.

set -e

REPO_ROOT="\$(git rev-parse --show-toplevel)"
PY="\$(command -v python3 || command -v python)"

if [[ -z "\$PY" ]]; then
    echo "pre-commit: no python on PATH; skipping checks" >&2
    exit 0
fi

# Prefer the venv'd python from python/.venv if it exists; the
# workspace check imports crucible.spec which lives there.
if [[ -x "\${REPO_ROOT}/python/.venv/bin/python" ]]; then
    PY="\${REPO_ROOT}/python/.venv/bin/python"
fi

\$PY "\${REPO_ROOT}/tools/check_workspace.py"
EOF

if [[ ${DRY_RUN} -eq 1 ]]; then
    echo "would write to: ${HOOK_PATH}"
    echo "--- hook content ---"
    echo "${HOOK_CONTENT}"
    echo "--- end ---"
    exit 0
fi

if [[ -e "${HOOK_PATH}" ]]; then
    if grep -q "${SENTINEL}" "${HOOK_PATH}"; then
        echo "pre-commit hook already installed (sentinel ${SENTINEL} found); refreshing in place"
    elif [[ ${FORCE} -eq 0 ]]; then
        echo "ERROR: existing pre-commit hook at ${HOOK_PATH} is NOT ours" >&2
        echo "       (no ${SENTINEL} sentinel). Use --force to overwrite." >&2
        exit 1
    else
        echo "warning: overwriting non-Crucible pre-commit hook (--force)" >&2
    fi
fi

mkdir -p "$(dirname "${HOOK_PATH}")"
printf "%s\n" "${HOOK_CONTENT}" > "${HOOK_PATH}"
chmod +x "${HOOK_PATH}"

echo "installed pre-commit hook at ${HOOK_PATH}"
echo "verify with: git commit --allow-empty -m 'test pre-commit'"
echo "skip with:   git commit --no-verify   (avoid in normal use)"
