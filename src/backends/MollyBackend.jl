# MollyBackend — native Julia path.
#
# Sweet spot: coarse-grained, implicit-solvent, small / pedagogical, anything
# autodifferentiable. Not the workhorse for solvated protein-ligand — the
# Router will send those to OpenMM.
#
# Like OpenMMBackend, v0 emits a Julia script (a Molly setup file) rather than
# directly evaluating Molly. Keeps the renderer testable without Molly
# installed in the test environment.

struct MollyBackend <: SimBackend
    name::Symbol
end

MollyBackend() = MollyBackend(:molly)

backend_name(b::MollyBackend) = b.name

function supported_features(::MollyBackend)::Set{Symbol}
    # Conservative claim of capabilities. Don't promote Molly past its proven
    # envelope here; the Router will fall through to OpenMM otherwise.
    Set([:nvt, :nve, :implicit_solvent, :thermostat, :langevin, :autodiff,
         :constraints])
end

function validate_spec(b::MollyBackend, spec::MDSpec)::ValidationReport
    r = ValidationReport()
    feats = supported_features(b)
    needed = required_features(spec)
    missing_feats = setdiff(needed, feats)
    if !isempty(missing_feats)
        r = record_error!(r,
            "MollyBackend cannot satisfy required features in v0: $(collect(missing_feats)). " *
            "Consider routing this spec to OpenMMBackend.")
    end
    return r
end

function estimate_resources(::MollyBackend, spec::MDSpec)::ResourceEstimate
    total_ns = sum(s isa DynamicsStage ? s.duration_ns : 0.0 for s in spec.protocol)
    ResourceEstimate(spec.system.n_atoms_estimate, total_ns, :molly,
        "Molly throughput is benchmarks-derived and ~0.2-0.4x of OpenMM on the same workload")
end

const _MOLLY_HEADER = "# Generated by Crucible MollyBackend - do not edit by hand.\n# Deterministic for a given MDSpec.\n\nusing Molly\nusing Unitful\n\n"

function render_script(::MollyBackend, spec::MDSpec; output_dir::AbstractString)::String
    io = IOBuffer()
    print(io, _MOLLY_HEADER)
    print(io, "const OUTPUT_DIR = ", repr(output_dir), "\n")
    print(io, "isdir(OUTPUT_DIR) || mkpath(OUTPUT_DIR)\n\n")

    src = spec.system.source
    if src.type == :user_supplied && src.coordinates !== nothing
        print(io, "# --- system load ---\n")
        print(io, "sys = System(", repr(src.coordinates), ";\n")
        if src.topology !== nothing
            print(io, "    topology_file = ", repr(src.topology), ",\n")
        end
        print(io, "    force_field = OpenMMForceField(",
                  _molly_ff_files_repr(spec.force_field), "),\n")
        print(io, "    units = (energy=u\"kJ * mol^-1\", length=u\"nm\", time=u\"ps\"),\n")
        print(io, ")\n\n")
    else
        print(io, "# v0 Molly renderer requires a user_supplied coordinates path.\n")
        print(io, "error(\"MollyBackend v0 requires SystemSource.coordinates\")\n")
    end

    for (i, stage) in enumerate(spec.protocol)
        if stage isa MinimizeStage
            print(io, "# Stage ", i, ": minimize\n")
            print(io, "Molly.simulate!(sys, SteepestDescentMinimizer(step_size=0.01u\"nm\", max_steps=",
                      stage.max_iterations, "); n_threads=Threads.nthreads())\n\n")
        elseif stage isa DynamicsStage
            n_steps = ns_to_steps(stage.duration_ns, stage.dt_fs)
            print(io, "# Stage ", i, ": ", String(stage.role), " (", String(stage.ensemble), ", ",
                      stage.duration_ns, " ns)\n")
            if stage.ensemble == :NPT
                print(io, "# WARNING: NPT in Molly v0 is not battle-tested; recommend routing to OpenMM.\n")
            end
            print(io, "sim = Langevin(\n")
            print(io, "    dt = ", stage.dt_fs, "u\"fs\",\n")
            print(io, "    temperature = ", stage.temperature_K, "u\"K\",\n")
            print(io, "    friction = ", stage.friction_ps, "u\"ps^-1\",\n")
            print(io, ")\n")
            stage_tag = string(String(stage.role), "_", i)
            print(io, "logger = (\n")
            print(io, "    energy = TotalEnergyLogger(typeof(1.0u\"kJ * mol^-1\"), 1000),\n")
            print(io, "    temp   = TemperatureLogger(typeof(1.0u\"K\"), 1000),\n")
            print(io, ")\n")
            print(io, "sys = System(sys; loggers=logger)\n")
            print(io, "Molly.simulate!(sys, sim, ", n_steps, "; n_threads=Threads.nthreads())\n")
            print(io, "# trajectory writeout for stage ", stage_tag, " is a v0.5 task\n\n")
        end
    end

    print(io, "println(\"Crucible Molly run complete: \$OUTPUT_DIR\")\n")
    String(take!(io))
end

function _molly_ff_files_repr(ff::ForceFieldSpec)
    parts = String[]
    if ff.protein == :amber14sb
        push!(parts, "\"amber14-all.xml\"")
    elseif ff.protein == :amber99sb_ildn
        push!(parts, "\"amber99sbildn.xml\"")
    end
    if ff.water == :TIP3P
        push!(parts, "\"amber14/tip3p.xml\"")
    elseif ff.water == :implicit_GBSA
        push!(parts, "\"implicit/gbn2.xml\"")
    end
    join(parts, ", ")
end

function prepare(b::MollyBackend, spec::MDSpec, workdir::AbstractString)::PreparedJob
    isdir(workdir) || mkpath(workdir)
    script_path = joinpath(workdir, "run_molly.jl")
    open(script_path, "w") do io
        print(io, render_script(b, spec; output_dir=workdir))
    end
    PreparedJob(:molly, workdir, script_path,
        Dict{String,Any}("script_size_bytes" => filesize(script_path)))
end

function preview_run(::MollyBackend, ::PreparedJob; n_steps::Int=100)::PreviewReport
    PreviewReport(true, true, nothing, nothing,
        ["MollyBackend preview_run is a v0 stub — wire Molly + a tiny test fixture to enable"])
end

function run!(b::MollyBackend, job::PreparedJob; on_progress=identity)::SimResult
    SimResult(job, false, String[],
        "MollyBackend.run! is a v0 stub. Run the script manually:\n  julia --project $(job.script_path)\nor wire direct Molly invocation once Molly is added to deps.")
end

function collect_artifacts(::MollyBackend, result::SimResult)::Vector{SimArtifact}
    arts = SimArtifact[]
    isdir(result.job.workdir) || return arts
    for f in readdir(result.job.workdir)
        kind = endswith(f, ".dcd") || endswith(f, ".xtc") ? :trajectory :
               endswith(f, ".log") ? :timeseries : :log
        push!(arts, SimArtifact(joinpath(result.job.workdir, f), kind, ""))
    end
    arts
end
