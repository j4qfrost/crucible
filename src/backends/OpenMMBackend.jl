# OpenMMBackend — the workhorse path.
#
# Renders an MDSpec to an executable OpenMM Python script using a deterministic
# template. v0 does NOT call PythonCall directly from this file — it produces
# the script and metadata; the runner is layered in once PythonCall is wired
# through CondaPkg. This keeps the renderer unit-testable without a Python env.

struct OpenMMBackend <: SimBackend
    python::String        # path to python (PythonCall handles this in production)
    name::Symbol
end

OpenMMBackend(; python="python") = OpenMMBackend(python, :openmm)

backend_name(b::OpenMMBackend) = b.name

function supported_features(::OpenMMBackend)::Set{Symbol}
    Set([:pme, :npt, :nvt, :nve, :explicit_solvent, :implicit_solvent, :ligand,
         :barostat, :thermostat, :constraints, :langevin, :monte_carlo, :gpu,
         :alchemy, :remd, :metadynamics, :biased_sampling, :plumed,
         :multi_replica, :membrane,
         # Scaffolding-only — IR roundtrips, validation passes, but the
         # renderer emits a NotImplementedError stub. v2 commits to a
         # real implementation; the IR shape is stable now.
         :constph, :titration, :coarse_grain])
end

function validate_spec(b::OpenMMBackend, spec::MDSpec)::ValidationReport
    r = ValidationReport()
    src = spec.system.source
    # BYO-topology gate: ligand + user-supplied FF + user_supplied source requires a topology path.
    # SMILES paths bypass this — the parameterizer generates the topology at prepare() time.
    if spec.system.has_ligand && spec.force_field.ligand == :user_supplied
        if src.type == :user_supplied && src.topology === nothing
            r = record_error!(r,
                "OpenMMBackend: ligand present + ligand_ff=user_supplied requires system.source.topology " *
                "(or switch source.type to :smiles / :protein_ligand for SMILES → OpenFF parameterization)")
        end
    end
    # PDBFixer auto-build is canonical-residues only — block ligand systems
    # via the protein-only :pdb_id / :pdb_fetch paths.
    if (src.type == :pdb_id || src.type == :pdb_fetch) && spec.system.has_ligand
        r = record_error!(r,
            "OpenMMBackend: pdb_fetch with has_ligand=true is unsupported; " *
            "use source.type=:protein_ligand (PDBFixer + OpenFF) instead")
    end
    if (src.type == :pdb_id || src.type == :pdb_fetch) && (src.pdb_id === nothing || isempty(src.pdb_id))
        r = record_error!(r,
            "OpenMMBackend: pdb_fetch source requires non-empty system.source.pdb_id")
    end
    # SMILES paths require a non-:user_supplied ligand FF.
    if src.type in (:smiles, :protein_ligand)
        if src.ligand_smiles === nothing || isempty(src.ligand_smiles)
            r = record_error!(r,
                "OpenMMBackend: source.type=$(src.type) requires non-empty ligand_smiles")
        end
        if spec.force_field.ligand == :user_supplied
            r = record_error!(r,
                "OpenMMBackend: source.type=$(src.type) requires force_field.ligand to be a " *
                "real parameterizer (e.g. :openff_sage_2_2_0); :user_supplied is incoherent here")
        end
        if !spec.system.has_ligand
            r = record_warning!(r,
                "OpenMMBackend: source.type=$(src.type) with has_ligand=false is unusual — did you mean true?")
        end
    end
    if src.type == :protein_ligand && (src.pdb_id === nothing || length(src.pdb_id) < 4)
        r = record_error!(r,
            "OpenMMBackend: source.type=:protein_ligand requires a 4-character pdb_id")
    end
    return r
end

function estimate_resources(::OpenMMBackend, spec::MDSpec)::ResourceEstimate
    total_ns = sum(s isa DynamicsStage ? s.duration_ns : 0.0 for s in spec.protocol)
    ResourceEstimate(spec.system.n_atoms_estimate, total_ns, :openmm,
        "scaled from OpenMM published throughputs in cloud/benchmarks.toml")
end

# -----------------------------------------------------------------------------
# Renderer
#
# String-template based. Mustache.jl is used elsewhere in the package; here
# we want deterministic ordering and total control over float formatting, so
# we hand-build the script. Golden-file tests pin the byte output.

const _OPENMM_SHEBANG = "#!/usr/bin/env python\n# Generated by Crucible OpenMMBackend — do not edit by hand.\n# This file is deterministic for a given MDSpec.\n"

function render_script(::OpenMMBackend, spec::MDSpec; output_dir::AbstractString)::String
    io = IOBuffer()
    print(io, _OPENMM_SHEBANG)
    print(io, "\n")
    print(io, "import sys, os, json\n")
    print(io, "from openmm import unit, LangevinMiddleIntegrator, MonteCarloBarostat, Platform\n")
    print(io, "from openmm.app import (Simulation, PDBFile, AmberPrmtopFile, AmberInpcrdFile,\n")
    print(io, "                        ForceField, Modeller, PME, HBonds, AllBonds, NoCutoff,\n")
    print(io, "                        StateDataReporter, DCDReporter)\n")
    print(io, "import numpy as np\n\n")

    print(io, "OUTPUT_DIR = ", repr(output_dir), "\n")
    print(io, "os.makedirs(OUTPUT_DIR, exist_ok=True)\n\n")

    print(io, _emit_system_load(spec))
    print(io, _emit_forcefield(spec))
    print(io, _emit_system_creation(spec))
    print(io, _emit_protonation(spec))
    print(io, _emit_protocol(spec))
    print(io, _emit_observables(spec))
    print(io, _emit_finalize(spec))

    String(take!(io))
end

function _emit_system_load(spec::MDSpec)
    src = spec.system.source
    io = IOBuffer()
    print(io, "# --- system load ---\n")
    if src.type == :user_supplied
        if src.coordinates === nothing
            error("OpenMM renderer: user_supplied source requires coordinates path")
        end
        if src.topology !== nothing && endswith(lowercase(src.topology), ".prmtop")
            # AMBER prmtop+inpcrd path
            print(io, "prmtop = AmberPrmtopFile(", repr(src.topology), ")\n")
            print(io, "inpcrd = AmberInpcrdFile(", repr(src.coordinates), ")\n")
            print(io, "topology = prmtop.topology\n")
            print(io, "positions = inpcrd.positions\n")
            print(io, "_use_amber = True\n")
        else
            # PDB-only path — topology comes from the PDB itself
            print(io, "pdb = PDBFile(", repr(src.coordinates), ")\n")
            print(io, "topology = pdb.topology\n")
            print(io, "positions = pdb.positions\n")
            print(io, "_use_amber = False\n")
        end
    elseif src.type == :smiles
        # Pure-ligand path. The parameterizer ran at prepare() time and wrote
        # ligand.parm7 / ligand.rst7 into the workdir; the script just loads
        # them as AMBER files. No protein, no PDBFixer.
        print(io, "prmtop = AmberPrmtopFile(os.path.join(OUTPUT_DIR, 'ligand.parm7'))\n")
        print(io, "inpcrd = AmberInpcrdFile(os.path.join(OUTPUT_DIR, 'ligand.rst7'))\n")
        print(io, "topology = prmtop.topology\n")
        print(io, "positions = inpcrd.positions\n")
        print(io, "_use_amber = True\n")
    elseif src.type == :protein_ligand
        # Protein + parameterized-ligand path. Runtime-only — no prepare-time
        # parameterization. Requires openff-toolkit + openmm-forcefields at
        # runtime (the renderer is environment-agnostic; the script imports
        # what it needs and fails loudly if missing).
        #
        #   1. PDBFixer fetches + repairs the protein.
        #   2. openff.toolkit loads the ligand from SMILES, generates a
        #      conformer, assigns AM1-BCC charges.
        #   3. SMIRNOFFTemplateGenerator (openmm-forcefields) registers the
        #      ligand against ForceField so a single System covers both.
        #   4. Modeller adds ligand to protein, optionally solvates.
        if src.pdb_id === nothing || isempty(src.pdb_id)
            error("OpenMM renderer: protein_ligand source requires non-empty pdb_id")
        end
        if src.ligand_smiles === nothing || isempty(src.ligand_smiles)
            error("OpenMM renderer: protein_ligand source requires non-empty ligand_smiles")
        end
        ligand_ff_str = spec.force_field.ligand == :openff_sage_2_2_0 ? "openff-2.2.0" :
                        spec.force_field.ligand == :gaff2             ? "gaff-2.11"   :
                        error("OpenMM renderer: protein_ligand requires force_field.ligand in (:openff_sage_2_2_0, :gaff2)")
        ligand_name = "LIG"
        print(io, "from pdbfixer import PDBFixer\n")
        print(io, "from openmm.unit import nanometer, molar\n")
        print(io, "from openff.toolkit import Molecule\n")
        print(io, "from openmmforcefields.generators import SMIRNOFFTemplateGenerator\n")
        print(io, "# 1. fetch + repair protein\n")
        print(io, "_fixer = PDBFixer(pdbid=", repr(src.pdb_id), ")\n")
        print(io, "_fixer.findMissingResidues()\n")
        print(io, "_fixer.findNonstandardResidues()\n")
        print(io, "_fixer.replaceNonstandardResidues()\n")
        print(io, "_fixer.removeHeterogens(keepWater=False)\n")
        print(io, "_fixer.findMissingAtoms()\n")
        print(io, "_fixer.addMissingAtoms()\n")
        print(io, "_fixer.addMissingHydrogens(7.0)\n")
        print(io, "# 2. parameterize ligand from SMILES\n")
        print(io, "_lig = Molecule.from_smiles(", repr(src.ligand_smiles), ", allow_undefined_stereo=True)\n")
        print(io, "_lig.name = ", repr(ligand_name), "\n")
        print(io, "_lig.generate_conformers(n_conformers=1)\n")
        print(io, "_lig.assign_partial_charges('am1bcc')\n")
        # Force-field XMLs
        ff_files = String[]
        if spec.force_field.protein == :amber14sb
            push!(ff_files, "amber14-all.xml")
        elseif spec.force_field.protein == :amber99sb_ildn
            push!(ff_files, "amber99sbildn.xml")
        elseif spec.force_field.protein == :amber03
            push!(ff_files, "amber03.xml")
        elseif spec.force_field.protein == :charmm36m
            push!(ff_files, "charmm36.xml")
        end
        if spec.system.solvent.model == :TIP3P
            push!(ff_files, "amber14/tip3p.xml")
        elseif spec.system.solvent.model == :TIP4P_EW
            push!(ff_files, "amber14/tip4pew.xml")
        elseif spec.system.solvent.model == :SPC_E
            push!(ff_files, "amber14/spce.xml")
        end
        files_repr = "[" * join((repr(f) for f in ff_files), ", ") * "]"
        print(io, "forcefield = ForceField(*", files_repr, ")\n")
        print(io, "_smirnoff = SMIRNOFFTemplateGenerator(molecules=[_lig], forcefield=", repr(ligand_ff_str), ")\n")
        print(io, "forcefield.registerTemplateGenerator(_smirnoff.generator)\n")
        print(io, "# 3. merge protein + ligand topologies\n")
        print(io, "_protein = Modeller(_fixer.topology, _fixer.positions)\n")
        print(io, "_lig_topology = _lig.to_topology().to_openmm()\n")
        print(io, "_lig_positions = _lig.conformers[0].to_openmm()\n")
        print(io, "_protein.add(_lig_topology, _lig_positions)\n")
        if spec.system.solvent.model in (:TIP3P, :TIP4P_EW, :SPC_E)
            water_model = spec.system.solvent.model == :TIP3P    ? "tip3p" :
                          spec.system.solvent.model == :TIP4P_EW ? "tip4pew" : "spce"
            ionic_M = spec.system.solvent.ions_NaCl_mM / 1000.0
            print(io, "_protein.addSolvent(forcefield, padding=1.0*nanometer, ionicStrength=",
                      ionic_M, "*molar, model=", repr(water_model), ")\n")
        end
        print(io, "_prepared_path = os.path.join(OUTPUT_DIR, ", repr("$(src.pdb_id)_complex.pdb"), ")\n")
        print(io, "with open(_prepared_path, 'w') as _ofh:\n")
        print(io, "    PDBFile.writeFile(_protein.topology, _protein.positions, _ofh)\n")
        print(io, "topology = _protein.topology\n")
        print(io, "positions = _protein.positions\n")
        print(io, "_use_amber = False\n")
    elseif src.type == :pdb_id || src.type == :pdb_fetch
        # PDBFixer auto-build path: only valid for canonical-residue
        # protein systems with no ligand. The renderer is gated above; the
        # script does the fetch + repair + (optional) solvate at runtime.
        if spec.system.has_ligand
            error("OpenMM renderer: pdb_fetch with has_ligand=true is unsupported in v0; use :protein_ligand")
        end
        if src.pdb_id === nothing || isempty(src.pdb_id)
            error("OpenMM renderer: pdb_fetch source requires non-empty pdb_id")
        end
        print(io, "from pdbfixer import PDBFixer\n")
        print(io, "from openmm.unit import nanometer, molar\n")
        print(io, "_fixer = PDBFixer(pdbid=", repr(src.pdb_id), ")\n")
        print(io, "_fixer.findMissingResidues()\n")
        print(io, "_fixer.findNonstandardResidues()\n")
        print(io, "_fixer.replaceNonstandardResidues()\n")
        print(io, "_fixer.findMissingAtoms()\n")
        print(io, "_fixer.addMissingAtoms()\n")
        print(io, "_fixer.addMissingHydrogens(7.0)\n")
        # In vacuum or implicit-solvent mode, drop crystallographic waters and
        # ions that ship in the PDB. They are not represented in the loaded
        # force field XML and ForceField.createSystem will fail on them.
        if spec.system.solvent.model in (:vacuum, :implicit_GBSA)
            print(io, "_fixer.removeHeterogens(keepWater=False)\n")
        end
        if spec.system.solvent.model in (:TIP3P, :TIP4P_EW, :SPC_E)
            water_model = spec.system.solvent.model == :TIP3P    ? "tip3p" :
                          spec.system.solvent.model == :TIP4P_EW ? "tip4pew" : "spce"
            ionic_M = spec.system.solvent.ions_NaCl_mM / 1000.0
            print(io, "_fixer.addSolvent(padding=1.0*nanometer, ionicStrength=",
                      ionic_M, "*molar, waterModel=", repr(water_model), ")\n")
        end
        print(io, "_prepared_path = os.path.join(OUTPUT_DIR, ", repr("$(src.pdb_id)_prepared.pdb"), ")\n")
        print(io, "from openmm.app import PDBFile as _PDBFileForWrite\n")
        print(io, "with open(_prepared_path, 'w') as _ofh:\n")
        print(io, "    _PDBFileForWrite.writeFile(_fixer.topology, _fixer.positions, _ofh)\n")
        print(io, "pdb = PDBFile(_prepared_path)\n")
        print(io, "topology = pdb.topology\n")
        print(io, "positions = pdb.positions\n")
        print(io, "_use_amber = False\n")
    else
        error("Unsupported source type: $(src.type)")
    end
    print(io, "\n")
    String(take!(io))
end

function _emit_forcefield(spec::MDSpec)
    ff = spec.force_field
    io = IOBuffer()
    # Coarse-grained protein FF: scaffolding-only stub. The Martini ecosystem
    # has multiple incompatible toolchains (martinize2 / vermouth / martini-
    # vampire); committing the renderer to one would lock us in. v2 picks.
    if ff.protein in (:martini3, :martini2_2)
        print(io, "# --- coarse-grained force field (v2 scaffolding stub) ---\n")
        print(io, "# Crucible v1.x ships the IR + validation only — runtime needs `martinize2`\n")
        print(io, "# (https://github.com/marrink-lab/vermouth-martinize) to convert atomistic\n")
        print(io, "# input to Martini topology, then `gmx grompp + mdrun` (or OpenMM\n")
        print(io, "# with the Martini OpenMM .xml that ships with vermouth) to integrate.\n")
        print(io, "raise NotImplementedError(\n")
        print(io, "    'crucible: Martini coarse-grained MD is v2-deferred. The IR is stable; '\n")
        print(io, "    'unblock locally by running martinize2 on your atomistic system, then '\n")
        print(io, "    'load the resulting topology with the Martini OpenMM XML.'\n")
        print(io, ")\n\n")
        return String(take!(io))
    end
    print(io, "# --- force field ---\n")
    ff_files = String[]
    if ff.protein == :amber14sb
        push!(ff_files, "amber14-all.xml")
    elseif ff.protein == :amber99sb_ildn
        push!(ff_files, "amber99sbildn.xml")
    elseif ff.protein == :amber03
        push!(ff_files, "amber03.xml")
    elseif ff.protein == :charmm36m
        push!(ff_files, "charmm36.xml")
    elseif ff.protein == :opls_aam
        print(io, "# WARNING: opls_aam requires user-supplied OPLS XML; falling back to amber14-all\n")
        push!(ff_files, "amber14-all.xml")
    end
    if ff.water == :TIP3P
        push!(ff_files, "amber14/tip3p.xml")
    elseif ff.water == :TIP4P_EW
        push!(ff_files, "amber14/tip4pew.xml")
    elseif ff.water == :SPC_E
        push!(ff_files, "amber14/spce.xml")
    elseif ff.water == :implicit_GBSA
        push!(ff_files, "implicit/gbn2.xml")
    end
    if ff.lipid !== nothing
        if ff.lipid == :charmm36_lipid
            push!(ff_files, "charmm36/lipid17.xml")
        elseif ff.lipid == :lipid21
            push!(ff_files, "amber14/lipid21.xml")
        elseif ff.lipid == :slipids
            print(io, "# NOTE: slipids requires user-supplied SLIPIDS XML; falling back to lipid21\n")
            push!(ff_files, "amber14/lipid21.xml")
        end
    end
    files_repr = "[" * join((repr(f) for f in ff_files), ", ") * "]"
    print(io, "if not _use_amber:\n")
    print(io, "    forcefield = ForceField(*", files_repr, ")\n")
    print(io, "\n")
    String(take!(io))
end

function _emit_system_creation(spec::MDSpec)
    io = IOBuffer()
    print(io, "# --- system creation ---\n")
    nonbonded = spec.system.solvent.model in (:TIP3P, :TIP4P_EW, :SPC_E) ? "PME" : "NoCutoff"
    has_constraints = any(s isa DynamicsStage && s.constraints != :none for s in spec.protocol)
    constraint_kind = has_constraints ? "HBonds" : "None"

    print(io, "if _use_amber:\n")
    print(io, "    system = prmtop.createSystem(nonbondedMethod=", nonbonded,
              ", nonbondedCutoff=1.0*unit.nanometer, constraints=", constraint_kind, ")\n")
    print(io, "else:\n")
    print(io, "    system = forcefield.createSystem(topology, nonbondedMethod=", nonbonded,
              ", nonbondedCutoff=1.0*unit.nanometer, constraints=", constraint_kind, ")\n")
    # NaCl ions
    if spec.system.solvent.ions_NaCl_mM > 0
        print(io, "# NOTE: ion neutralization assumes the system was prepared with the correct\n")
        print(io, "# ion count for ", spec.system.solvent.ions_NaCl_mM, " mM NaCl. v0 does not auto-add ions.\n")
    end
    print(io, "\n")
    String(take!(io))
end

function _emit_protocol(spec::MDSpec)
    io = IOBuffer()
    print(io, "# --- protocol ---\n")
    # Platform selection. CRUCIBLE_PLATFORM forces a specific platform
    # ('CUDA' / 'HIP' / 'OpenCL' / 'CPU' / 'Reference'); 'auto' (default)
    # tries each in order and falls through. This means an AMD box with
    # gfx1100 + ROCm gets HIP automatically; a no-GPU CI machine gets CPU.
    print(io, "def _crucible_pick_platform():\n")
    print(io, "    req = os.environ.get('CRUCIBLE_PLATFORM', 'auto')\n")
    print(io, "    if req != 'auto':\n")
    print(io, "        return Platform.getPlatformByName(req)\n")
    print(io, "    for _name in ('CUDA', 'HIP', 'OpenCL', 'CPU'):\n")
    print(io, "        try:\n")
    print(io, "            return Platform.getPlatformByName(_name)\n")
    print(io, "        except Exception:\n")
    print(io, "            continue\n")
    print(io, "    return Platform.getPlatformByName('Reference')\n")
    print(io, "platform = _crucible_pick_platform()\n")
    # Precision control. CRUCIBLE_PRECISION ∈ {single, mixed, double},
    # default `mixed`. Only applies to CUDA/HIP/OpenCL — CPU + Reference
    # ignore the property. Done at platform-level so all stages share it.
    print(io, "_precision = os.environ.get('CRUCIBLE_PRECISION', 'mixed')\n")
    print(io, "if _precision not in ('single', 'mixed', 'double'):\n")
    print(io, "    print(f'crucible: WARNING: CRUCIBLE_PRECISION={_precision} is not single|mixed|double; using mixed')\n")
    print(io, "    _precision = 'mixed'\n")
    print(io, "if platform.getName() in ('CUDA', 'HIP', 'OpenCL'):\n")
    print(io, "    platform.setPropertyDefaultValue('Precision', _precision)\n")
    print(io, "print('crucible: platform =', platform.getName(), 'precision =', _precision)\n")
    # Preview gate: when CRUCIBLE_PREVIEW_STEPS is set, every dynamics stage
    # caps n_steps at that value. Lets validation Gate 4 reuse this script.
    print(io, "_preview_cap = int(os.environ['CRUCIBLE_PREVIEW_STEPS']) if 'CRUCIBLE_PREVIEW_STEPS' in os.environ else None\n")
    print(io, "def _cap(n): return min(n, _preview_cap) if _preview_cap is not None else n\n")
    print(io, "current_positions = positions\n")
    print(io, "current_velocities = None\n\n")

    for (i, stage) in enumerate(spec.protocol)
        if stage isa FEPStage
            print(io, _emit_fep_stage(stage, i))
            continue
        end
        if stage isa REMDStage
            print(io, _emit_remd_stage(stage, i))
            continue
        end
        if stage isa MetadynamicsStage
            print(io, _emit_metadynamics_stage(stage, i))
            continue
        end
        if stage isa MinimizeStage
            print(io, "# Stage ", i, ": minimize\n")
            print(io, "_min_integrator = LangevinMiddleIntegrator(300*unit.kelvin, 1.0/unit.picosecond, 0.001*unit.picoseconds)\n")
            print(io, "_sim = Simulation(topology, system, _min_integrator, platform)\n")
            print(io, "_sim.context.setPositions(current_positions)\n")
            print(io, "_sim.minimizeEnergy(tolerance=", stage.tolerance_kj_mol_nm,
                      "*unit.kilojoule_per_mole/unit.nanometer, maxIterations=", stage.max_iterations, ")\n")
            print(io, "_state = _sim.context.getState(getPositions=True)\n")
            print(io, "current_positions = _state.getPositions(asNumpy=True)\n")
            print(io, "del _sim, _min_integrator\n\n")
        elseif stage isa DynamicsStage
            n_steps = ns_to_steps(stage.duration_ns, stage.dt_fs)
            print(io, "# Stage ", i, ": ", String(stage.role), " (", String(stage.ensemble), ", ",
                      stage.duration_ns, " ns)\n")
            if stage.ensemble == :NVE
                # Microcanonical: Verlet integrator, no thermostat, no barostat.
                # NVE expects velocities to be set already (typically from a
                # prior NVT equilibration or temperature draw at the first step).
                print(io, "from openmm import VerletIntegrator\n")
                print(io, "_integrator = VerletIntegrator(", stage.dt_fs, "*unit.femtoseconds)\n")
            else
                if stage.thermostat != :langevin
                    print(io, "# WARNING: thermostat=", String(stage.thermostat),
                              " requested but Crucible v0 only emits LangevinMiddleIntegrator.\n")
                end
                print(io, "_integrator = LangevinMiddleIntegrator(", stage.temperature_K,
                          "*unit.kelvin, ", stage.friction_ps, "/unit.picosecond, ",
                          stage.dt_fs, "*unit.femtoseconds)\n")
            end
            # NPT: add barostat as a force in the system, then create the simulation.
            # Membrane systems use MonteCarloMembraneBarostat for semi-isotropic
            # coupling (XY isotropic, Z independent — physically correct for bilayers).
            if stage.ensemble == :NPT
                p = stage.pressure_bar === nothing ? 1.0 : stage.pressure_bar
                if spec.system.solvent.membrane !== nothing
                    print(io, "from openmm import MonteCarloMembraneBarostat\n")
                    print(io, "_baro = MonteCarloMembraneBarostat(", p, "*unit.bar, ",
                              "0.0*unit.bar*unit.nanometer, ",   # surface tension γ=0
                              stage.temperature_K, "*unit.kelvin,\n",
                              "    MonteCarloMembraneBarostat.XYIsotropic, ",
                              "MonteCarloMembraneBarostat.ZFree, 25)\n")
                else
                    print(io, "_baro = MonteCarloBarostat(", p, "*unit.bar, ",
                              stage.temperature_K, "*unit.kelvin, 25)\n")
                end
                print(io, "_baro_index = system.addForce(_baro)\n")
            end
            print(io, "_sim = Simulation(topology, system, _integrator, platform)\n")
            print(io, "_sim.context.setPositions(current_positions)\n")
            print(io, "if current_velocities is not None:\n")
            print(io, "    _sim.context.setVelocities(current_velocities)\n")
            print(io, "else:\n")
            print(io, "    _sim.context.setVelocitiesToTemperature(", stage.temperature_K, "*unit.kelvin)\n")

            # Reporters scoped to this stage
            stage_tag = string(String(stage.role), "_", i)
            log_period = max(1, ns_to_steps(0.001, stage.dt_fs))   # ~1 ps log cadence
            print(io, "_sim.reporters.append(StateDataReporter(\n")
            print(io, "    os.path.join(OUTPUT_DIR, ", repr("$(stage_tag).log"), "),\n")
            print(io, "    ", log_period, ", step=True, time=True, potentialEnergy=True,\n")
            print(io, "    kineticEnergy=True, totalEnergy=True, temperature=True, volume=True))\n")

            # Per-spec trajectory reporters — DCDReporter at the requested
            # stride, written to <stage>_traj.dcd. Only attached for stages
            # that include the trajectory observable.
            for o in spec.observables
                o.type == :trajectory || continue
                stride_steps = max(1, ps_to_steps(o.stride_ps, stage.dt_fs))
                print(io, "_sim.reporters.append(DCDReporter(\n")
                print(io, "    os.path.join(OUTPUT_DIR, ", repr("$(stage_tag)_traj.dcd"), "),\n")
                print(io, "    ", stride_steps, "))\n")
            end

            # Restraints — harmonic positional restraints anchored at current_positions
            _has_restraints = stage.restraints.selection != :none && stage.restraints.k_kj_mol_nm2 > 0
            if _has_restraints
                if stage.restraints.kind != :harmonic
                    print(io, "# WARNING: restraint kind=", String(stage.restraints.kind),
                              " requested; v0.1 emits harmonic only.\n")
                end
                _sel = stage.restraints.selection
                _select_expr = _sel == :heavy_atoms ? "atom.element.symbol != 'H'" :
                               _sel == :backbone   ? "atom.name in ('N','CA','C','O')" :
                               _sel == :ca         ? "atom.name == 'CA'" :
                               error("unknown restraint selection $(_sel)")
                print(io, "from openmm import CustomExternalForce\n")
                print(io, "_restraint = CustomExternalForce('0.5*k*((x-x0)*(x-x0)+(y-y0)*(y-y0)+(z-z0)*(z-z0))')\n")
                print(io, "_restraint.addGlobalParameter('k', ", stage.restraints.k_kj_mol_nm2,
                          "*unit.kilojoule_per_mole/unit.nanometer**2)\n")
                print(io, "_restraint.addPerParticleParameter('x0')\n")
                print(io, "_restraint.addPerParticleParameter('y0')\n")
                print(io, "_restraint.addPerParticleParameter('z0')\n")
                print(io, "for atom in topology.atoms():\n")
                print(io, "    if ", _select_expr, ":\n")
                print(io, "        _p = current_positions[atom.index].value_in_unit(unit.nanometer)\n")
                print(io, "        _restraint.addParticle(atom.index, [_p[0], _p[1], _p[2]])\n")
                print(io, "_restraint_index = system.addForce(_restraint)\n")
                print(io, "_sim.context.reinitialize(preserveState=True)\n")
            end

            # Run
            print(io, "_sim.step(_cap(", n_steps, "))\n")
            print(io, "_state = _sim.context.getState(getPositions=True, getVelocities=True)\n")
            print(io, "current_positions = _state.getPositions(asNumpy=True)\n")
            print(io, "current_velocities = _state.getVelocities(asNumpy=True)\n")

            # Tear down restraint for the next stage
            if _has_restraints
                print(io, "system.removeForce(_restraint_index)\n")
            end
            # Tear down barostat for the next stage if the ensemble changes
            if stage.ensemble == :NPT
                print(io, "system.removeForce(_baro_index)\n")
            end
            print(io, "del _sim, _integrator\n\n")
        end
    end
    String(take!(io))
end

