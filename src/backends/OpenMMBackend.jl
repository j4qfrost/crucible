# Prepare / preview / run

function prepare(b::OpenMMBackend, spec::MDSpec, workdir::AbstractString;
                 parameterizer::Union{Nothing,LigandParameterizer}=nothing)::PreparedJob
    isdir(workdir) || mkpath(workdir)
    metadata = Dict{String,Any}()

    # SMILES path — generate ligand.parm7 / ligand.rst7 in the workdir.
    # The renderer's _emit_system_load loads them as AMBER files. The
    # parameterizer only runs for :smiles; :protein_ligand parameterizes at
    # script-runtime via SMIRNOFFTemplateGenerator.
    if spec.system.source.type == :smiles
        p = parameterizer === nothing ? OpenFFParameterizer() : parameterizer
        smiles = spec.system.source.ligand_smiles
        smiles === nothing && error("OpenMMBackend.prepare: :smiles source requires ligand_smiles")
        result = parameterize(p, smiles, workdir)
        metadata["ligand_topology"]    = result.topology_path
        metadata["ligand_coordinates"] = result.coordinates_path
        metadata["ligand_forcefield"]  = String(result.forcefield_name)
        metadata["ligand_metadata"]    = result.metadata
    end

    script_path = joinpath(workdir, "run_openmm.py")
    open(script_path, "w") do io
        print(io, render_script(b, spec; output_dir=workdir))
    end
    metadata["script_size_bytes"] = filesize(script_path)
    PreparedJob(:openmm, workdir, script_path, metadata)
end

function preview_run(b::OpenMMBackend, job::PreparedJob; n_steps::Int=100)::PreviewReport
    # Smoke gate. Runs the prepared script with CRUCIBLE_PREVIEW_STEPS set,
    # which the renderer honors at execution time (shortens every dynamics
    # stage to n_steps). Asserts: process exited cleanly + last energy line
    # has no NaN/Inf.
    isfile(job.script_path) || return PreviewReport(false, false, nothing, nothing,
        ["preview_run: prepared script missing: $(job.script_path)"])
    log_path = joinpath(job.workdir, "preview_stdout.log")
    env = copy(ENV)
    env["CRUCIBLE_PREVIEW_STEPS"] = string(n_steps)
    cmd = pipeline(setenv(`$(b.python) $(job.script_path)`, env);
                   stdout=log_path, stderr=log_path)
    ok = false
    log_text = ""
    try
        proc = run(cmd; wait=true)
        ok = proc.exitcode == 0
    catch err
        log_text = "preview run failed: $(err)\n"
    end
    if isfile(log_path)
        log_text *= read(log_path, String)
    end
    energies_finite = !occursin(r"NaN|Infinity|-?[0-9]+e\+30", log_text)
    PreviewReport(ok && energies_finite, energies_finite, nothing, nothing,
        ok ? ["preview run completed in $(n_steps) steps"] :
             ["preview run failed; see $(log_path)"])
end

function run!(b::OpenMMBackend, job::PreparedJob; on_progress=identity)::SimResult
    isfile(job.script_path) ||
        return SimResult(job, false, String[], "OpenMMBackend.run!: script not prepared")
    log_path = joinpath(job.workdir, "stdout.log")
    cmd = pipeline(`$(b.python) $(job.script_path)`; stdout=log_path, stderr=log_path)
    success = false
    log_text = ""
    try
        proc = run(cmd; wait=true)
        success = proc.exitcode == 0
    catch err
        log_text = "execution failed: $(err)\n"
    end
    if isfile(log_path)
        log_text *= read(log_path, String)
    end
    artifacts = [joinpath(job.workdir, f) for f in readdir(job.workdir)]
    SimResult(job, success, artifacts, log_text)
end

function collect_artifacts(::OpenMMBackend, result::SimResult)::Vector{SimArtifact}
    arts = SimArtifact[]
    isdir(result.job.workdir) || return arts
    for f in readdir(result.job.workdir)
        kind = endswith(f, ".dcd") ? :trajectory :
               endswith(f, ".log") ? :timeseries :
               endswith(f, ".chk") ? :checkpoint : :log
        push!(arts, SimArtifact(joinpath(result.job.workdir, f), kind, ""))
    end
    arts
end
