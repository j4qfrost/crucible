# OpenMMBackend — the workhorse path.
#
# Renders an MDSpec to an executable OpenMM Python script using a deterministic
# template. v0 does NOT call PythonCall directly from this file — it produces
# the script and metadata; the runner is layered in once PythonCall is wired
# through CondaPkg. This keeps the renderer unit-testable without a Python env.

struct OpenMMBackend <: SimBackend
    python::String        # path to python (PythonCall handles this in production)
    name::Symbol
end

OpenMMBackend(; python="python") = OpenMMBackend(python, :openmm)

backend_name(b::OpenMMBackend) = b.name

function supported_features(::OpenMMBackend)::Set{Symbol}
    Set([:pme, :npt, :nvt, :nve, :explicit_solvent, :implicit_solvent, :ligand,
         :barostat, :thermostat, :constraints, :langevin, :monte_carlo, :gpu])
end

function validate_spec(b::OpenMMBackend, spec::MDSpec)::ValidationReport
    r = ValidationReport()
    # All currently-modeled features are supported by OpenMM, so the only
    # backend-specific check we need is the BYO-topology contract: if there's
    # a ligand and the FF is :user_supplied, the user must have provided a
    # topology file.
    if spec.system.has_ligand && spec.force_field.ligand == :user_supplied
        if spec.system.source.topology === nothing
            r = record_error!(r,
                "OpenMMBackend: ligand present + ligand_ff=user_supplied requires system.source.topology")
        end
    end
    return r
end

function estimate_resources(::OpenMMBackend, spec::MDSpec)::ResourceEstimate
    total_ns = sum(s isa DynamicsStage ? s.duration_ns : 0.0 for s in spec.protocol)
    ResourceEstimate(spec.system.n_atoms_estimate, total_ns, :openmm,
        "scaled from OpenMM published throughputs in cloud/benchmarks.toml")
end

# -----------------------------------------------------------------------------
# Renderer
#
# String-template based. Mustache.jl is used elsewhere in the package; here
# we want deterministic ordering and total control over float formatting, so
# we hand-build the script. Golden-file tests pin the byte output.

const _OPENMM_SHEBANG = "#!/usr/bin/env python\n# Generated by Crucible OpenMMBackend — do not edit by hand.\n# This file is deterministic for a given MDSpec.\n"

function render_script(::OpenMMBackend, spec::MDSpec; output_dir::AbstractString)::String
    io = IOBuffer()
    write(io, _OPENMM_SHEBANG)
    write(io, "\n")
    write(io, "import sys, os, json\n")
    write(io, "from openmm import unit, LangevinMiddleIntegrator, MonteCarloBarostat, Platform\n")
    write(io, "from openmm.app import (Simulation, PDBFile, AmberPrmtopFile, AmberInpcrdFile,\n")
    write(io, "                        ForceField, Modeller, PME, HBonds, AllBonds, NoCutoff,\n")
    write(io, "                        StateDataReporter, DCDReporter)\n")
    write(io, "import numpy as np\n\n")

    write(io, "OUTPUT_DIR = ", repr(output_dir), "\n")
    write(io, "os.makedirs(OUTPUT_DIR, exist_ok=True)\n\n")

    write(io, _emit_system_load(spec))
    write(io, _emit_forcefield(spec))
    write(io, _emit_system_creation(spec))
    write(io, _emit_protocol(spec))
    write(io, _emit_observables(spec))
    write(io, _emit_finalize(spec))

    String(take!(io))
end

function _emit_system_load(spec::MDSpec)
    src = spec.system.source
    io = IOBuffer()
    write(io, "# --- system load ---\n")
    if src.type == :user_supplied
        if src.topology === nothing || src.coordinates === nothing
            error("OpenMM renderer: user_supplied source requires topology + coordinates paths")
        end
        if endswith(lowercase(src.topology), ".prmtop")
            write(io, "prmtop = AmberPrmtopFile(", repr(src.topology), ")\n")
            write(io, "inpcrd = AmberInpcrdFile(", repr(src.coordinates), ")\n")
            write(io, "topology = prmtop.topology\n")
            write(io, "positions = inpcrd.positions\n")
            write(io, "_use_amber = True\n")
        else
            write(io, "pdb = PDBFile(", repr(src.coordinates), ")\n")
            write(io, "topology = pdb.topology\n")
            write(io, "positions = pdb.positions\n")
            write(io, "_use_amber = False\n")
        end
    elseif src.type == :pdb_id
        write(io, "from openmm.app.internal.pdbstructure import PdbStructure\n")
        write(io, "raise NotImplementedError('pdb_id source path is v0.5; supply topology+coordinates for v0')\n")
    else
        error("Unsupported source type: $(src.type)")
    end
    write(io, "\n")
    String(take!(io))
end

function _emit_forcefield(spec::MDSpec)
    ff = spec.force_field
    io = IOBuffer()
    write(io, "# --- force field ---\n")
    ff_files = String[]
    if ff.protein == :amber14sb
        push!(ff_files, "amber14-all.xml")
    elseif ff.protein == :amber99sb_ildn
        push!(ff_files, "amber99sbildn.xml")
    elseif ff.protein == :amber03
        push!(ff_files, "amber03.xml")
    elseif ff.protein == :charmm36m
        push!(ff_files, "charmm36.xml")
    elseif ff.protein == :opls_aam
        # OPLS-AA/M needs a separate XML; flag for user
        write(io, "# WARNING: opls_aam requires user-supplied OPLS XML; falling back to amber14-all\n")
        push!(ff_files, "amber14-all.xml")
    end
    if ff.water == :TIP3P
        push!(ff_files, "amber14/tip3p.xml")
    elseif ff.water == :TIP4P_EW
        push!(ff_files, "amber14/tip4pew.xml")
    elseif ff.water == :SPC_E
        push!(ff_files, "amber14/spce.xml")
    elseif ff.water == :implicit_GBSA
        push!(ff_files, "implicit/gbn2.xml")
    elseif ff.water == :vacuum
        # no water FF
    end
    files_repr = "[" * join((repr(f) for f in ff_files), ", ") * "]"
    write(io, "if not _use_amber:\n")
    write(io, "    forcefield = ForceField(*", files_repr, ")\n")
    write(io, "\n")
    String(take!(io))
end

function _emit_system_creation(spec::MDSpec)
    io = IOBuffer()
    write(io, "# --- system creation ---\n")
    nonbonded = spec.system.solvent.model in (:TIP3P, :TIP4P_EW, :SPC_E) ? "PME" : "NoCutoff"
    has_constraints = any(s isa DynamicsStage && s.constraints != :none for s in spec.protocol)
    constraint_kind = has_constraints ? "HBonds" : "None"

    write(io, "if _use_amber:\n")
    write(io, "    system = prmtop.createSystem(nonbondedMethod=", nonbonded,
              ", nonbondedCutoff=1.0*unit.nanometer, constraints=", constraint_kind, ")\n")
    write(io, "else:\n")
    write(io, "    system = forcefield.createSystem(topology, nonbondedMethod=", nonbonded,
              ", nonbondedCutoff=1.0*unit.nanometer, constraints=", constraint_kind, ")\n")
    # NaCl ions
    if spec.system.solvent.ions_NaCl_mM > 0
        write(io, "# NOTE: ion neutralization assumes the system was prepared with the correct\n")
        write(io, "# ion count for ", spec.system.solvent.ions_NaCl_mM, " mM NaCl. v0 does not auto-add ions.\n")
    end
    write(io, "\n")
    String(take!(io))
end

function _emit_protocol(spec::MDSpec)
    io = IOBuffer()
    write(io, "# --- protocol ---\n")
    write(io, "platform = Platform.getPlatformByName(os.environ.get('CRUCIBLE_PLATFORM', 'CUDA'))\n")
    write(io, "current_positions = positions\n")
    write(io, "current_velocities = None\n\n")

    for (i, stage) in enumerate(spec.protocol)
        if stage isa MinimizeStage
            write(io, "# Stage ", i, ": minimize\n")
            write(io, "_min_integrator = LangevinMiddleIntegrator(300*unit.kelvin, 1.0/unit.picosecond, 0.001*unit.picoseconds)\n")
            write(io, "_sim = Simulation(topology, system, _min_integrator, platform)\n")
            write(io, "_sim.context.setPositions(current_positions)\n")
            write(io, "_sim.minimizeEnergy(tolerance=", stage.tolerance_kj_mol_nm,
                      "*unit.kilojoule_per_mole/unit.nanometer, maxIterations=", stage.max_iterations, ")\n")
            write(io, "_state = _sim.context.getState(getPositions=True)\n")
            write(io, "current_positions = _state.getPositions(asNumpy=True)\n")
            write(io, "del _sim, _min_integrator\n\n")
        elseif stage isa DynamicsStage
            n_steps = ns_to_steps(stage.duration_ns, stage.dt_fs)
            write(io, "# Stage ", i, ": ", String(stage.role), " (", String(stage.ensemble), ", ",
                      stage.duration_ns, " ns)\n")
            if stage.thermostat != :langevin
                write(io, "# WARNING: thermostat=", String(stage.thermostat),
                          " requested but Crucible v0 only emits LangevinMiddleIntegrator.\n")
            end
            write(io, "_integrator = LangevinMiddleIntegrator(", stage.temperature_K,
                      "*unit.kelvin, ", stage.friction_ps, "/unit.picosecond, ",
                      stage.dt_fs, "*unit.femtoseconds)\n")
            # NPT: add barostat as a force in the system, then create the simulation
            if stage.ensemble == :NPT
                p = stage.pressure_bar === nothing ? 1.0 : stage.pressure_bar
                write(io, "_baro = MonteCarloBarostat(", p, "*unit.bar, ",
                          stage.temperature_K, "*unit.kelvin, 25)\n")
                write(io, "_baro_index = system.addForce(_baro)\n")
            end
            write(io, "_sim = Simulation(topology, system, _integrator, platform)\n")
            write(io, "_sim.context.setPositions(current_positions)\n")
            write(io, "if current_velocities is not None:\n")
            write(io, "    _sim.context.setVelocities(current_velocities)\n")
            write(io, "else:\n")
            write(io, "    _sim.context.setVelocitiesToTemperature(", stage.temperature_K, "*unit.kelvin)\n")

            # Reporters scoped to this stage
            stage_tag = string(String(stage.role), "_", i)
            log_period = max(1, ns_to_steps(0.001, stage.dt_fs))   # ~1 ps log cadence
            write(io, "_sim.reporters.append(StateDataReporter(\n")
            write(io, "    os.path.join(OUTPUT_DIR, ", repr("$(stage_tag).log"), "),\n")
            write(io, "    ", log_period, ", step=True, time=True, potentialEnergy=True,\n")
            write(io, "    kineticEnergy=True, totalEnergy=True, temperature=True, volume=True))\n")

            # Restraints
            if stage.restraints.selection != :none && stage.restraints.k_kj_mol_nm2 > 0
                write(io, "# WARNING: restraints requested (", String(stage.restraints.selection), ", k=",
                          stage.restraints.k_kj_mol_nm2, " kJ/mol/nm^2)\n")
                write(io, "# v0 emits a comment; restraint force injection lands in v0.5.\n")
            end

            # Run
            write(io, "_sim.step(", n_steps, ")\n")
            write(io, "_state = _sim.context.getState(getPositions=True, getVelocities=True)\n")
            write(io, "current_positions = _state.getPositions(asNumpy=True)\n")
            write(io, "current_velocities = _state.getVelocities(asNumpy=True)\n")

            # Tear down barostat for the next stage if the ensemble changes
            if stage.ensemble == :NPT
                write(io, "system.removeForce(_baro_index)\n")
            end
            write(io, "del _sim, _integrator\n\n")
        end
    end
    String(take!(io))
end

function _emit_observables(spec::MDSpec)
    io = IOBuffer()
    write(io, "# --- observables (v0: emitted as documentation; analysis lives in PlutoRenderer) ---\n")
    for o in spec.observables
        write(io, "# observable: type=", String(o.type), " selection=", repr(o.selection),
                  " stride_ps=", o.stride_ps, "\n")
    end
    write(io, "\n")
    String(take!(io))
end

function _emit_finalize(::MDSpec)
    """\
    # --- finalize ---
    print(json.dumps({"status": "ok", "output_dir": OUTPUT_DIR}))
    """
end

# -----------------------------------------------------------------------------
# Prepare / preview / run

function prepare(b::OpenMMBackend, spec::MDSpec, workdir::AbstractString)::PreparedJob
    isdir(workdir) || mkpath(workdir)
    script_path = joinpath(workdir, "run_openmm.py")
    open(script_path, "w") do io
        write(io, render_script(b, spec; output_dir=workdir))
    end
    PreparedJob(:openmm, workdir, script_path,
        Dict{String,Any}("script_size_bytes" => filesize(script_path)))
end

function preview_run(::OpenMMBackend, ::PreparedJob; n_steps::Int=100)::PreviewReport
    # v0: returns a not-yet-implemented preview. Wiring the actual
    # PythonCall-driven preview is gated behind a CondaPkg-installed env.
    PreviewReport(true, true, nothing, nothing,
        ["preview_run is a v0 stub — wire PythonCall + CondaPkg env to enable",
         "rendered script is saved at the prepared job's script_path; you can run it manually"])
end

function run!(b::OpenMMBackend, job::PreparedJob; on_progress=identity)::SimResult
    SimResult(job, false, String[],
        "OpenMMBackend.run! is a v0 stub. Run the script manually:\n  python $(job.script_path)\nor wire PythonCall once CondaPkg env is installed.")
end

function collect_artifacts(::OpenMMBackend, result::SimResult)::Vector{SimArtifact}
    arts = SimArtifact[]
    isdir(result.job.workdir) || return arts
    for f in readdir(result.job.workdir)
        kind = endswith(f, ".dcd") ? :trajectory :
               endswith(f, ".log") ? :timeseries :
               endswith(f, ".chk") ? :checkpoint : :log
        push!(arts, SimArtifact(joinpath(result.job.workdir, f), kind, ""))
    end
    arts
end
